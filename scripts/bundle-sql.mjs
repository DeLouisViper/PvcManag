// Concatenates supabase/migrations/*.sql into ONE file you can paste into the Supabase SQL editor.
import { readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const dir = join(dirname(fileURLToPath(import.meta.url)), '../supabase')
const files = readdirSync(join(dir, 'migrations')).filter((f) => f.endsWith('.sql')).sort()
const out = ['-- HAIC PVC Material Manager: complete database setup (generated by `npm run db:bundle`)', '-- Paste into Supabase > SQL Editor > New query > Run. Run it ONCE on an empty project.', '']
for (const f of files) out.push(`-- ===================== ${f} =====================`, readFileSync(join(dir, 'migrations', f), 'utf8'), '')
writeFileSync(join(dir, 'setup_all.sql'), out.join('\n'))
console.log(`supabase/setup_all.sql written from ${files.length} migrations`)
